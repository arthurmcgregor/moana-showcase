#!/usr/bin/env python3
"""TTF -> VLW (M5GFX smooth font), plus an optional C header wrapping the bytes.

VLW is the only anti-aliased font format M5GFX can load at runtime. The layout
below was read off the loader in
M5GFX/src/lgfx/Fonts/lgfx_fonts.cpp (VLWfont::loadFont / drawChar):

  header   6 x uint32 big-endian: gCount, version(11), fontSize, mboxY,
                                  ascent, descent
  metrics  gCount x 7 x uint32 BE: unicode, height, width, xAdvance, dY, dX, 0
  bitmaps  concatenated in metric order, 8-bit alpha, width*height bytes each

Two constraints the loader imposes and this encoder honours:
  * glyph records must be sorted ascending by codepoint — getUnicodeIndex()
    does a std::lower_bound over the unicode table
  * bitmap order must match metric order — the loader accumulates bitmap
    offsets while walking the metrics, it never seeks per glyph

Note: M5GFX ignores the space glyph's advance and substitutes its own guess
(yAdvance * 2/7), so word spacing is not ours to control.

No OpenType feature support here on purpose. Features are frozen into the TTF
upstream (pyftfeatfreeze -f tnum) so that both this encoder and lv_font_conv,
neither of which shapes text, pick up the tabular digits from cmap.
"""

import argparse
import struct
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

VLW_VERSION = 11


def glyph_bitmap(font, ch):
    """Render one glyph to (width, height, dX, dY, xAdvance, alpha bytes).

    dX is the left bearing and dY the height of the glyph above the baseline,
    both in the sign convention the M5GFX loader expects.
    """
    bbox = font.getbbox(ch, anchor="ls")
    x0, y0, x1, y1 = bbox
    w, h = x1 - x0, y1 - y0
    advance = round(font.getlength(ch))

    if w <= 0 or h <= 0:  # space and friends carry no ink
        return 0, 0, 0, 0, advance, b""

    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    return w, h, x0, -y0, advance, img.tobytes()


def encode(ttf, size, charset):
    font = ImageFont.truetype(str(ttf), size)
    ascent, descent = font.getmetrics()

    metrics, bitmaps = bytearray(), bytearray()
    # Sorted: getUnicodeIndex() binary-searches the codepoint table.
    for ch in sorted(set(charset)):
        cp = ord(ch)
        if cp > 0xFFFF:
            raise ValueError(f"VLW is BMP-only, cannot encode U+{cp:04X}")
        w, h, dx, dy, advance, bits = glyph_bitmap(font, ch)
        metrics += struct.pack(">7I", cp, h, w, advance, dy & 0xFFFFFFFF, dx & 0xFFFFFFFF, 0)
        bitmaps += bits

    count = len(set(charset))
    header = struct.pack(">6I", count, VLW_VERSION, size, size, ascent, descent)
    return bytes(header + metrics + bitmaps), count


def as_header(blob, name, ttf, size, count):
    rows = []
    for i in range(0, len(blob), 16):
        rows.append("    " + " ".join(f"0x{b:02X}," for b in blob[i:i + 16]))
    body = "\n".join(rows)
    return f"""// Generated by tools/fonts/vlw_encode.py — do not edit by hand.
// Source: {ttf.name} @ {size}px, {count} glyphs, {len(blob)} bytes.
// Load with: M5.Display.loadFont({name});
#pragma once

#include <cstdint>

alignas(4) inline constexpr uint8_t {name}[] = {{
{body}
}};
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("ttf", type=Path)
    ap.add_argument("--size", type=int, required=True, help="pixel size")
    ap.add_argument("--charset", default="ascii", help="'ascii' (0x20-0x7E), 'digits' (0-9 . : -), or a literal string")
    ap.add_argument("--out", type=Path, required=True, help=".vlw output path")
    ap.add_argument("--header", type=Path, help="also emit a C header wrapping the bytes")
    ap.add_argument("--name", help="C array name (defaults to the header stem)")
    args = ap.parse_args()

    if args.charset == "ascii":
        charset = "".join(chr(c) for c in range(0x20, 0x7F))
    elif args.charset == "digits":
        charset = "0123456789.:- "
    else:
        charset = args.charset

    blob, count = encode(args.ttf, args.size, charset)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(blob)
    print(f"{args.out}  {count} glyphs  {len(blob):,} bytes", file=sys.stderr)

    if args.header:
        name = args.name or args.header.stem
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(as_header(blob, name, args.ttf, args.size, count))
        print(f"{args.header}  ({name})", file=sys.stderr)


if __name__ == "__main__":
    main()
