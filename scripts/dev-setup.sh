#!/usr/bin/env bash
#
# One-time local development setup: env files, Python venv, npm packages.
#
# Idempotent — every step is skipped if it is already done, so it is safe to
# re-run after pulling changes. Nothing here touches secret.env or prod.env;
# those belong to the production stack.
#
# Usage: scripts/dev-setup.sh   (or: mise run dev:setup)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVER_DIR="$ROOT/server"
FRONTEND_DIR="$ROOT/frontend"

RED=$'\033[31m'; GREEN=$'\033[32m'; YELLOW=$'\033[33m'; RESET=$'\033[0m'
say()  { printf '%s==>%s %s\n' "$GREEN" "$RESET" "$1"; }
skip() { printf '    %s(already done)%s %s\n' "$YELLOW" "$RESET" "$1"; }
warn() { printf '%sWarning:%s %s\n' "$YELLOW" "$RESET" "$1" >&2; }
die()  { printf '%sError:%s %s\n' "$RED" "$RESET" "$1" >&2; exit 1; }

# Appended to server/.env whether the file is written fresh below or already exists.
# Deployed, Authelia supplies the staff identity; locally these do.
DEV_ADMIN_BLOCK="# Local admin, dev only — settings.py ignores all three unless DEBUG is on.
# With DEV_AUTO_LOGIN on, Django fakes the Remote-User header Authelia sends in
# production, as DEV_ADMIN_USERNAME, so the frontend shows the editing UI without
# a login form. Set it to 0 to browse as an anonymous visitor instead. The password
# is only for /admin/; 'mise run dev:admin' sets it.
DEV_ADMIN_USERNAME=admin
DEV_ADMIN_PASSWORD=admin
DEV_AUTO_LOGIN=1"

# --- 1. server/.env ------------------------------------------------------------
#
# Written from .env.example but re-pointed at the *host*: the example targets the
# containerised stack (POSTGRES_HOST=db), whereas local Django runs on the host and
# reaches the dev database over the published port. The password must match the one
# hard-coded in server/docker-compose.yml.

if [[ -f "$SERVER_DIR/.env" ]]; then
  skip "server/.env exists — leaving it alone"
else
  say "Writing server/.env for host-side development..."
  secret="$(python3 -c 'import secrets,string; print("".join(secrets.choice(string.ascii_lowercase+string.digits+"!@#$%^&*(-_=+)") for _ in range(50)))')"
  cat > "$SERVER_DIR/.env" <<EOF
# Local development. Generated by scripts/dev-setup.sh — edit freely, it is gitignored.
# The production stack uses prod.env + secret.env at the repo root instead.

# Django (dev settings.py hard-codes DEBUG and its own key; these matter to settings_prod.py)
DJANGO_SECRET_KEY=$secret
DJANGO_ALLOWED_HOSTS=localhost,127.0.0.1

# PostgreSQL. server/docker-compose.yml interpolates these same values, so this
# file configures the container and host-side Django at once. Port 5436 rather
# than 5432, which is contested on most dev machines.
POSTGRES_DB=moana
POSTGRES_USER=moana_user
POSTGRES_PASSWORD=secure_password
POSTGRES_HOST=localhost
POSTGRES_PORT=5436

# CORS / CSRF — the Vite dev server origin
CORS_ALLOWED_ORIGINS=http://localhost:5173
CSRF_TRUSTED_ORIGINS=http://localhost:5173

# Gunicorn (unused by runserver; kept so the file mirrors prod.env)
GUNICORN_WORKERS=3
GUNICORN_TIMEOUT=120

# Host port mapping
WEB_PORT=8000

# Immich integration (blank disables it; photo endpoints return an empty list)
IMMICH_URL=
IMMICH_API_KEY=
IMMICH_PUBLIC_URL=

$DEV_ADMIN_BLOCK
EOF
fi

# Older .env files predate the dev admin knobs. settings.py defaults to the same
# values, so this is only about making them visible and editable.
if ! grep -q '^DEV_ADMIN_USERNAME=' "$SERVER_DIR/.env"; then
  say "Adding the dev admin settings to server/.env..."
  printf '\n%s\n' "$DEV_ADMIN_BLOCK" >> "$SERVER_DIR/.env"
fi

# --- 2. GEOS / GDAL ------------------------------------------------------------
#
# GeoDjango dlopens these; settings.py looks for the Homebrew copies.

if [[ "$(uname -s)" == "Darwin" ]]; then
  if [[ -f /opt/homebrew/lib/libgdal.dylib && -f /opt/homebrew/lib/libgeos_c.dylib ]]; then
    skip "GDAL and GEOS found in /opt/homebrew/lib"
  else
    warn "GDAL/GEOS not found in /opt/homebrew/lib — GeoDjango will fail to import.
         Install them with: brew install gdal geos
         (or point GDAL_LIBRARY_PATH / GEOS_LIBRARY_PATH at your own copies)"
  fi
fi

# --- 3. Python venv ------------------------------------------------------------

if [[ -x "$SERVER_DIR/.venv/bin/python" ]]; then
  skip "server/.venv exists"
else
  say "Creating server/.venv..."
  command -v mise >/dev/null 2>&1 || die "mise is not installed — see https://mise.jdx.dev"
  # mise owns the Python version pin (server/mise.toml) and creates the venv on first
  # use of the directory; `mise install` fetches the interpreter if it is missing.
  (cd "$SERVER_DIR" && mise install && mise exec -- python -m venv .venv)
fi

say "Installing Python dependencies (server/requirements.txt)..."
"$SERVER_DIR/.venv/bin/python" -m pip install --quiet --upgrade pip
"$SERVER_DIR/.venv/bin/python" -m pip install --quiet -r "$SERVER_DIR/requirements.txt"

# --- 4. frontend/.env.local ----------------------------------------------------

if [[ -f "$FRONTEND_DIR/.env.local" ]]; then
  skip "frontend/.env.local exists"
else
  say "Writing frontend/.env.local..."
  cat > "$FRONTEND_DIR/.env.local" <<'EOF'
# Local development. Gitignored. src/config.ts already defaults the two base URLs
# to http://moana.local (device) and http://localhost:8000 (Django), so the only
# value that must be filled in is the Mapbox token — without it the map is blank.
VITE_MAPBOX_ACCESS_TOKEN=
EOF
  warn "frontend/.env.local needs a VITE_MAPBOX_ACCESS_TOKEN before the map will render."
fi

if [[ -z "$(grep -E '^VITE_MAPBOX_ACCESS_TOKEN=.+' "$FRONTEND_DIR/.env.local" || true)" ]]; then
  warn "VITE_MAPBOX_ACCESS_TOKEN is empty in frontend/.env.local — the map will be blank."
fi

# --- 5. npm packages -----------------------------------------------------------

say "Installing frontend dependencies..."
if [[ -f "$FRONTEND_DIR/package-lock.json" ]]; then
  (cd "$FRONTEND_DIR" && npm ci --silent)
else
  (cd "$FRONTEND_DIR" && npm install --silent)
fi

# --- done ----------------------------------------------------------------------

cat <<EOF

${GREEN}Setup complete.${RESET}

  mise run dev          full stack — database, Django on :8000, Vite on :5173
  mise run dev:db       database only
  mise run dev:admin    create/refresh the local admin account
  mise run dev:down     stop the database
  mise run test         server test suite (its own throwaway DB on :5434)

You are an admin locally without doing anything: Django fakes the Remote-User
header Authelia sends in production, as DEV_ADMIN_USERNAME from server/.env.
DEV_AUTO_LOGIN=0 turns that off to browse as a visitor. admin/admin logs you
in at http://localhost:8000/admin/ either way.
EOF
